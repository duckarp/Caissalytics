using Caissalytics.Core;
using Xunit;

namespace Caissalytics.Tests;

public class PgnRoundTripTests
{
    private static List<string> Mainline(GameTree tree)
    {
        var sans = new List<string>();
        var node = tree.Root;
        while (node.Children.Count > 0)
        {
            node = node.Children[0];
            sans.Add(node.San);
        }
        return sans;
    }

    [Fact]
    public void HeaderWithQuotesAndBackslash_SurvivesExportAndImport()
    {
        var tree = PgnHandler.ImportPgn("[Event \"Club \\\"Rapid\\\" Cup\"]\n[Site \"C:\\\\chess\"]\n\n1. e4 e5 *");
        Assert.Equal("Club \"Rapid\" Cup", tree.Headers["Event"]);
        Assert.Equal("C:\\chess", tree.Headers["Site"]);

        var reimported = PgnHandler.ImportPgn(PgnHandler.ExportPgn(tree));

        Assert.Equal("Club \"Rapid\" Cup", reimported.Headers["Event"]);
        Assert.Equal("C:\\chess", reimported.Headers["Site"]);
        Assert.Equal(new[] { "e4", "e5" }, Mainline(reimported));
    }

    [Fact]
    public void CommentContainingClosingBrace_DoesNotBreakReimport()
    {
        var tree = PgnHandler.ImportPgn("1. e4 e5 2. Nf3 *");
        tree.Root.Children[0].Comment = "set {a} trap";

        var reimported = PgnHandler.ImportPgn(PgnHandler.ExportPgn(tree));

        Assert.Equal(new[] { "e4", "e5", "Nf3" }, Mainline(reimported));
        Assert.Contains("trap", reimported.Root.Children[0].Comment);
    }

    [Fact]
    public void TagInsideComment_IsNotTreatedAsHeader()
    {
        var tree = PgnHandler.ImportPgn("[Event \"Main\"]\n\n1. e4 {compare [Event \"Other\"]} e5 *");

        Assert.Equal("Main", tree.Headers["Event"]);
        Assert.Equal(new[] { "e4", "e5" }, Mainline(tree));
        Assert.Contains("Other", tree.Root.Children[0].Comment);
    }

    [Fact]
    public void RestOfLineComment_IsNotPlayedAsMoves()
    {
        // "d5" in the comment is a legal reply to 1.e4
        var tree = PgnHandler.ImportPgn("1. e4 ; maybe d5 is better\ne5 2. Nf3 *");

        Assert.Equal(new[] { "e4", "e5", "Nf3" }, Mainline(tree));
        Assert.Equal("maybe d5 is better", tree.Root.Children[0].Comment);
    }

    [Fact]
    public void PercentEscapeLine_IsIgnored()
    {
        var tree = PgnHandler.ImportPgn("%generated by tool d5 Nf3\n1. e4 e5 *");

        Assert.Equal(new[] { "e4", "e5" }, Mainline(tree));
    }

    [Fact]
    public void IllegalMove_StopsThatLineInsteadOfReplayingFromAWrongPosition()
    {
        // Mainline: Ke3 is illegal for Black; old code skipped it and went on to play Nc6
        var tree = PgnHandler.ImportPgn("1. e4 e5 2. Nf3 Ke3 3. Bc4 Nc6 *");
        Assert.Equal(new[] { "e4", "e5", "Nf3" }, Mainline(tree));
        Assert.Equal("*", tree.Headers["Result"]);

        // Inside a variation only that variation is cut; the mainline continues after it
        var withVariation = PgnHandler.ImportPgn("1. e4 (1. d4 Ke5 2. c4) 1... e5 2. Nf3 *");
        Assert.Equal(new[] { "e4", "e5", "Nf3" }, Mainline(withVariation));
        var variation = Assert.Single(withVariation.Root.Children.Skip(1));
        Assert.Equal("d4", variation.San);
        Assert.Empty(variation.Children);
    }

    [Fact]
    public void StrayAnnotationTokens_AreStillIgnored()
    {
        var tree = PgnHandler.ImportPgn("1. e4 !? e5 N 2. Nf3 *");

        Assert.Equal(new[] { "e4", "e5", "Nf3" }, Mainline(tree));
    }

    [Fact]
    public void PromotionWithoutEqualsSign_IsAccepted()
    {
        var tree = PgnHandler.ImportPgn("[SetUp \"1\"]\n[FEN \"8/4P3/8/8/8/8/k7/4K3 w - - 0 1\"]\n\n1. e8Q Kb2 *");

        Assert.Equal(new[] { "e8=Q", "Kb2" }, Mainline(tree));
    }

    [Fact]
    public void CommentLineBreaks_SurviveImportAndExport()
    {
        var tree = PgnHandler.ImportPgn("1. e4 {First line\r\n  second   line\n\n\n\nnew paragraph} e5 *");
        var e4 = tree.Root.Children[0];
        Assert.Equal("First line\nsecond line\n\nnew paragraph", e4.Comment);

        var reimported = PgnHandler.ImportPgn(PgnHandler.ExportPgn(tree));

        Assert.Equal(e4.Comment, reimported.Root.Children[0].Comment);
        Assert.Equal(new[] { "e4", "e5" }, Mainline(reimported));
    }

    [Fact]
    public void CommentWithClock_KeepsLineBreaks()
    {
        var tree = PgnHandler.ImportPgn("1. e4 {[%clk 0:05:00] Plan:\nkingside attack} *");
        var e4 = tree.Root.Children[0];
        Assert.Equal("0:05:00", e4.Clock);
        Assert.Equal("Plan:\nkingside attack", e4.Comment);
    }
}
