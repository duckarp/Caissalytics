namespace Caissalytics.Data;

/// <summary>
/// Deterministic offline ECO (Encyclopaedia of Chess Openings) classifier.
/// Walks the mainline SAN moves over a static move tree built from the
/// standard ECO list. Returns the deepest ECO code whose line is matched
/// (or the deepest tagged ancestor when the game diverges from the tree,
/// mirroring Lichess ECO semantics), or <c>null</c> when no ECO line matches.
/// </summary>
public static class EcoClassifier
{
    private class TrieNode
    {
        public Dictionary<string, TrieNode>? Children;
        public string? Eco;
    }

    /// <summary>
    /// Classifies a game from its mainline SAN moves.
    /// </summary>
    /// <param name="sanMoves">Mainline SAN moves in game order (may include check/checkmate and annotation suffixes).</param>
    public static string? Classify(IReadOnlyList<string> sanMoves)
    {
        if (sanMoves == null || sanMoves.Count == 0)
        {
            return null;
        }

        var node = Root;
        string? lastEco = null;
        foreach (var raw in sanMoves)
        {
            if (node.Eco is not null)
            {
                lastEco = node.Eco;
            }

            if (node.Children is null || !node.Children.TryGetValue(Normalize(raw), out var child))
            {
                return lastEco;
            }

            node = child;
        }

        return node.Eco ?? lastEco;
    }

    /// <summary>Normalizes a SAN token for tree matching (strips check/annotation suffixes, canonicalizes castling).</summary>
    public static string Normalize(string move)
    {
        var m = move.Trim();
        int i = m.Length;
        while (i > 0 && "+#?!;".IndexOf(m[i - 1]) >= 0)
        {
            i--;
        }

        switch (m[..i])
        {
            case "0-0":
            case "o-o":
                return "O-O";
            case "0-0-0":
            case "o-o-o":
                return "O-O-O";
            default:
                return m[..i];
        }
    }

    private static TrieNode BuildTree()
    {
        var root = new TrieNode();
        foreach (var (code, moves) in EcoTable)
        {
            var node = root;
            foreach (var mv in moves)
            {
                node.Children ??= new Dictionary<string, TrieNode>(StringComparer.Ordinal);
                if (!node.Children.TryGetValue(mv, out var child))
                {
                    child = new TrieNode();
                    node.Children[mv] = child;
                }
                node = child;
            }
            node.Eco = code;
        }
        return root;
    }

